import { compile, RADIUS_SCALE, spaceId } from "./compile";
import { COMPONENTS } from "./components";
import { SPACE_STEPS, TOKENS } from "./registry";
import type { DesignSystem, EasingValue, ShadowValue, Value } from "./types";
import { valueToCss } from "./values";

/* Exports: compiled CSS, Tailwind v4 theme, TypeScript tokens, W3C design tokens (DTCG). */

export type ExportFormat = "css" | "tailwind" | "ts" | "w3c" | "json";
export const EXPORT_FORMATS: Array<{ id: ExportFormat; label: string; file: (id: string) => string }> = [
  { id: "css", label: "CSS (variables + compiled rules)", file: (id) => `${id}.normy.css` },
  { id: "tailwind", label: "Tailwind v4 theme", file: (id) => `${id}.tailwind.css` },
  { id: "ts", label: "TypeScript tokens", file: (id) => `${id}.tokens.ts` },
  { id: "w3c", label: "W3C design tokens (DTCG)", file: (id) => `${id}.tokens.json` },
  { id: "json", label: "Normy system (JSON)", file: (id) => `${id}.normy.json` },
];

function resolved(system: DesignSystem) {
  return TOKENS.map((def) => {
    const light: Value = system.tokens[def.id] ?? def.default ?? null;
    const dark: Value | undefined = system.dark[def.id] ?? def.darkDefault;
    return { def, light, dark, lightCss: valueToCss(def, light, false), darkCss: dark !== undefined ? valueToCss(def, dark, false) : null };
  });
}

export function exportSystem(system: DesignSystem, format: ExportFormat): string {
  switch (format) {
    case "css":
      return `/* ${system.meta.name} — generated by Normy (${new Date().toISOString().slice(0, 10)}). Toggle dark mode with the .dark class on <html>. */\n${compile(system, COMPONENTS).css}`;
    case "json":
      return JSON.stringify(system, null, 2);
    case "tailwind":
      return toTailwind(system);
    case "ts":
      return toTs(system);
    case "w3c":
      return JSON.stringify(toW3C(system), null, 2);
  }
}

function toTailwind(system: DesignSystem) {
  const rows = resolved(system);
  const vars = rows.filter((r) => r.def.cssVar && r.lightCss !== null);
  const map: string[] = [];
  for (const r of vars) {
    const [group, ...rest] = r.def.id.split(".");
    const name = rest.join("-");
    const ns = { color: "color", font: "font", text: "text", radius: "radius", shadow: "shadow", easing: "ease", blur: "blur", tracking: "tracking", leading: "leading", weight: "font-weight" }[group];
    if (ns) map.push(`  --${ns}-${name}: var(${r.def.cssVar});`);
  }
  for (const [k] of RADIUS_SCALE) map.push(`  --radius-${k}: var(--n-radius-${k});`);
  map.push(`  --spacing: calc(var(--n-space-unit) * var(--n-space-density));`);
  const light = vars.map((r) => `  ${r.def.cssVar}: ${r.lightCss};`).join("\n");
  const dark = rows.filter((r) => r.def.cssVar && r.darkCss).map((r) => `  ${r.def.cssVar}: ${r.darkCss};`).join("\n");
  return `/* ${system.meta.name} — Tailwind v4 theme generated by Normy. */
@import "tailwindcss";
@custom-variant dark (&:where(.dark, .dark *));

:root {
${light}
  --n-radius-xs: calc(var(--n-radius-base) * 0.5); --n-radius-sm: calc(var(--n-radius-base) * 0.75); --n-radius-md: var(--n-radius-base);
  --n-radius-lg: calc(var(--n-radius-base) * 1.75); --n-radius-xl: calc(var(--n-radius-base) * 2.5); --n-radius-2xl: calc(var(--n-radius-base) * 4); --n-radius-none: 0px; --n-radius-full: 9999px;
}
.dark {
${dark}
}

@theme inline {
  --color-*: initial;
${map.join("\n")}
}
`;
}

const valueOut = (v: Value | undefined, css: string | null) => (v && typeof v === "object" ? css : v);

function toTs(system: DesignSystem) {
  const out: Record<string, Record<string, unknown>> = {};
  for (const r of resolved(system)) {
    const [group, ...rest] = r.def.id.split(".");
    const key = rest.join("-");
    out[group] ??= {};
    out[group][key] = r.dark !== undefined ? { light: valueOut(r.light, r.lightCss), dark: valueOut(r.dark, r.darkCss) } : valueOut(r.light, r.lightCss);
  }
  out.space = Object.fromEntries(SPACE_STEPS.map((n) => [spaceId(n), `var(--n-space-${spaceId(n)})`]));
  return `/* ${system.meta.name} — design tokens generated by Normy. Values are raw CSS. */
export const tokens = ${JSON.stringify(out, null, 2)} as const;

export type Tokens = typeof tokens;
`;
}

function w3cType(group: string): string {
  return ({ color: "color", font: "fontFamily", weight: "fontWeight", duration: "duration", easing: "cubicBezier", shadow: "shadow", leading: "number", opacity: "number", z: "number", motion: "string", bp: "dimension" } as Record<string, string>)[group] ?? "dimension";
}

function w3cValue(v: Value, css: string | null): unknown {
  if (v && typeof v === "object") {
    if (v.kind === "shadow") return (v as ShadowValue).layers.map((l) => ({ offsetX: `${l.x}px`, offsetY: `${l.y}px`, blur: `${l.blur}px`, spread: `${l.spread}px`, color: l.color, inset: !!l.inset }));
    if (v.kind === "easing") {
      const e = v as EasingValue;
      return e.type === "bezier" ? e.p : css;
    }
    return css;
  }
  if (typeof v === "number") return v;
  return v;
}

function toW3C(system: DesignSystem) {
  const root: Record<string, Record<string, unknown>> = { $description: { value: `${system.meta.name} — ${system.meta.description ?? ""}` } as never };
  delete root.$description;
  for (const r of resolved(system)) {
    const [group, ...rest] = r.def.id.split(".");
    const key = rest.join("-");
    root[group] ??= {};
    const token: Record<string, unknown> = { $type: w3cType(group), $value: w3cValue(r.light, r.lightCss), $description: r.def.label };
    if (r.dark !== undefined) token.$extensions = { "dev.normy.modes": { dark: w3cValue(r.dark, r.darkCss) } };
    root[group][key] = token;
  }
  return { $schema: "https://design-tokens.github.io/community-group/format/", ...root };
}
