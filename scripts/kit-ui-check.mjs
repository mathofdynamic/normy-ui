// Studio: Guide panel + Agent Kit download. URL=http://localhost:3001 node scripts/kit-ui-check.mjs
import { mkdirSync, readFileSync } from "node:fs";
import { launch } from "./launch-browser.mjs";
const BASE = process.env.URL ?? "http://localhost:3001";
mkdirSync("screenshots/kit", { recursive: true });
const b = await launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true });
await ctx.addInitScript(() => localStorage.setItem("normy:studio-welcomed", "1"));
const p = await ctx.newPage();
const errors = [];
p.on("pageerror", (e) => errors.push(String(e)));
let ok = true;
const check = (name, cond) => { console.log(`${cond ? "PASS" : "FAIL"}  ${name}`); ok &&= !!cond; };
await p.goto(BASE + "/studio", { waitUntil: "load" });
await p.getByRole("button", { name: /^Guide/ }).first().click();
await p.waitForTimeout(400);
check("guide panel opens", await p.getByRole("heading", { name: "Guide" }).isVisible());
await p.getByLabel("How should it feel?").fill("Calm and premium, one confident blue.");
await p.getByRole("radio", { name: "Never do" }).click();
await p.getByLabel("New rule").fill("Use more than one accent colour on a screen");
await p.getByRole("button", { name: "Add", exact: true }).click();
check("rule added", await p.getByText("Use more than one accent colour on a screen").isVisible());
await p.getByRole("switch", { name: /Craft details/ }).click();
check("pack switched off", (await p.getByRole("switch", { name: /Craft details/ }).getAttribute("aria-checked")) === "false");
await p.screenshot({ path: "screenshots/kit/guide-1440.png" });
await p.getByRole("button", { name: /Export the Agent Kit/ }).click();
await p.waitForTimeout(400);
check("export shows agent kit", await p.getByTestId("agent-kit").isVisible());
const pre = await p.locator(".st-kit pre").textContent();
check("preview has feel + rule", pre.includes("Calm and premium") && pre.includes("Never:** Use more than one accent"));
check("preview drops switched-off pack", !pre.includes("### Craft details"));
await p.screenshot({ path: "screenshots/kit/export-1440.png" });
const [dl] = await Promise.all([p.waitForEvent("download"), p.getByRole("button", { name: /Download Agent Kit/ }).click()]);
const path = "screenshots/kit/kit.zip";
await dl.saveAs(path);
const buf = readFileSync(path);
const s = buf.toString("latin1");
check("zip downloaded", buf.length > 100000 && buf.readUInt32LE(0) === 0x04034b50);
check("zip has SKILL.md, components, scripts", ["normy/SKILL.md", "normy/components/button.tsx", "normy/scripts/check.mjs", "normy/scripts/audit.mjs", "normy/styles/normy.css", "normy/fonts.ts"].every((f) => s.includes(f)));
check("zip skill carries the rule", s.includes("Use more than one accent colour on a screen"));
await p.setViewportSize({ width: 390, height: 844 });
await p.waitForTimeout(300);
await p.screenshot({ path: "screenshots/kit/export-390.png" });
check("no page errors", errors.length === 0);
if (errors.length) console.log(errors);
await b.close();
process.exitCode = ok ? 0 : 1;
