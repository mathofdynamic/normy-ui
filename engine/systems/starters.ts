type Pair = [string, string];
/** Build light + dark colour maps from [light, dark] pairs. */
function colors(map: Record<string, Pair>): { tokens: Props; dark: Props } {
  const tokens: Props = {};
  const dark: Props = {};
  for (const [k, [l, d]] of Object.entries(map)) {
    tokens[`color.${k}`] = l;
    dark[`color.${k}`] = d;
  }
  return { tokens, dark };
}
const sh = (...layers: Array<[number, number, number, number, string, boolean?]>) => ({
  kind: "shadow" as const,
  layers: layers.map(([x, y, blur, spread, color, inset]) => ({ x, y, blur, spread, color, inset })),
});
const bz = (p: [number, number, number, number]) => ({ kind: "easing" as const, type: "bezier" as const, p });
const spring = (stiffness: number, damping: number, mass = 1) => ({ kind: "easing" as const, type: "spring" as const, stiffness, damping, mass });

